package export

import (
	"fmt"
	"strings"
)

// readmeMD renders readme.md, the project's front door: what the system is,
// every token family the sheet emits (enumerated from the same tables the
// CSS emitter renders from, so the two cannot drift), the step purposes,
// pointers to the foundation pages, and the reproducibility
// contract theme.json carries.
func readmeMD(s Snapshot) string {
	var b strings.Builder

	b.WriteString("# Vibrant Gio — design tokens\n\n")
	fmt.Fprintf(&b, "Vibrant Gio is a generative design system for [Gio](https://gioui.org) desktop\n"+
		"applications. The entire colour system derives from one brand seed — currently\n"+
		"`%s` — through `theme/tokens.FromSeed`: every colour role carries a\n"+
		"**nine-step functional ramp (100–900)** on a shared lightness scale, with the\n"+
		"role's **base pinned separately** so the brand colour is reproduced exactly, and\n"+
		"**dark mode is the paired ramp** — the same step keeps the same job in both\n"+
		"modes, so nothing is assigned twice. The contrast gate is APCA\n"+
		"(step 900 reaches |Lc| 90 and step 700 |Lc| 60 over the 100/200 surfaces, every\n"+
		"pin's on-colour |Lc| 60 over its pin); WCAG 2 ratios are reported alongside but\n"+
		"do not gate.\n\n", hexRGB(s.Seed))

	b.WriteString("This directory is generated by `theme/export` (`cmd/vg-tokens`); do not edit\n" +
		"it by hand — regenerate it.\n\n")

	b.WriteString("## Files\n\n" +
		"- `styles.css` — the token sheet: one `:root` block (light colours and\n" +
		"  elevation levels plus every mode-invariant scale, comfortable density),\n" +
		"  one `.dark` class override block (the paired dark colours and levels)\n" +
		"  and one `.compact` class override block (the\n" +
		"  compact density metrics only). Add `class=\"dark\"` to the root element to\n" +
		"  switch modes, `class=\"compact\"` to any subtree to densify it; the two\n" +
		"  switches are orthogonal. Below the token blocks sits the component class\n" +
		"  layer (`.btn` and its modifiers) — see Component classes.\n" +
		"- `theme.json` — the generative parameters; see the reproducibility contract\n" +
		"  below.\n" +
		"- `foundations/color.html` — every ramp, pin, step purpose and measured\n" +
		"  APCA Lc / WCAG ratio per text pair, in both modes.\n" +
		"- `foundations/type.html` — every type role at its real metrics.\n" +
		"- `fonts/` — the faces behind `--font-family` and `--font-family-code`,\n" +
		"  self-hosted with their licences: the same Roboto regular and medium the\n" +
		"  Gio applications embed, and Roboto Mono from the font repository.\n" +
		"- `foundations/layout.html` — the spacing scale, the control metrics at both\n" +
		"  density settings, the radius scale and tonal elevation as rendered\n" +
		"  specimens.\n" +
		"- `components/*.html` — hand-authored component pages (not generated):\n" +
		"  every class-layer component in every variant and state, at both\n" +
		"  densities, as copyable markup. `buttons.html` covers `.btn` and `.badge`,\n" +
		"  `forms.html` the native-element form controls.\n\n" +
		"Each page reads only from `styles.css` — every styled value is a `var(--…)`\n" +
		"reference — and carries a light/dark toggle. Annotation numbers are printed for\n" +
		"both modes, labelled `L` and `D`.\n\n")

	b.WriteString("## Token families\n\n")
	b.WriteString("| Family | Tokens | Notes |\n| --- | --- | --- |\n")
	for _, role := range rampRoles {
		fmt.Fprintf(&b, "| `--color-%[1]s-<step>` | `--color-%[1]s-100` … `--color-%[1]s-900` | the %[1]s ramp; steps in hundreds |\n", role.name)
	}
	pinNames := make([]string, len(pinRoles))
	for i, pin := range pinRoles {
		pinNames[i] = "`--color-" + pin.name + "`"
	}
	fmt.Fprintf(&b, "| pins & semantic layer | %s | pinned bases, their on-colours, the ramp-resolved surface/divider, the inverse pair the counterpart scheme's ramp resolves, the reserved highlighter no status hue may serve, and the edges and rings each ramp measures for itself — a resting border for the page, the dialog and the popover, and one focus ring for the whole scheme, measured against every level at once, plus the accent fill a filled button's ring lies on, which belongs to no level at all |\n", strings.Join(pinNames, ", "))
	b.WriteString("| `--font-family` | `--font-family` | the typeface every prose role uses |\n")
	b.WriteString("| `--font-family-code` | `--font-family-code` | the monospace typeface the code role uses |\n")
	typeNames := make([]string, len(typeRoles))
	for i, role := range typeRoles {
		typeNames[i] = role.name
	}
	fmt.Fprintf(&b, "| `--font-<role>-*` | roles %s; each with `-size`, `-line-height`, `-weight`, `-tracking` | px sizes, CSS numeric weights; code is the mono style outside the MD3 grid, at body-medium's metrics |\n", strings.Join(typeNames, ", "))
	fmt.Fprintf(&b, "| `--density-<metric>` | %s, `--density-min-hit-target` | control metrics, px; `:root` is comfortable, `.compact` overrides all but the hit-target floor |\n", joinTokens("--density-", densityNames()))
	fmt.Fprintf(&b, "| `--space-<key>` | %s | the 4-pt spacing grid, px |\n", joinTokens("--space-", spaceNames()))
	fmt.Fprintf(&b, "| `--radius-<key>` | %s | corner radii, Tailwind naming, px |\n", joinTokens("--radius-", radiusNames()))
	fmt.Fprintf(&b, "| `--elevation-<level>` | %s | tonal surface fills — the DEFAULT elevation cue; ordered from the backdrop up toward the reader, and resolved per scheme, so both blocks state their own six |\n", joinTokens("--elevation-", elevationNames()))
	fmt.Fprintf(&b, "| `--elevation-<level>-seam` | %s | the hairline a raise draws at its own edge where the scheme has no step left to tell it by fill — `transparent` where the fill tells it. The backdrop has none: nothing stands on the backdrop |\n", joinTokens("--elevation-", elevationSeamNames()))
	fmt.Fprintf(&b, "| `--elevation-<level>-hairline` | %s | the hairline two regions that SHARE a level's fill are parted by — what a group draws at its own edge, and never `transparent`, because a group has no fill of its own and the line is the whole of what says where it ends. The backdrop has none: nothing is grouped on the bare window plane |\n", joinTokens("--elevation-", elevationHairlineNames()))
	fmt.Fprintf(&b, "| `--elevation-<level>-<state>` | %s | each level's own interaction walk — what a control with no fill of its own takes the surface under it to when hovered or pressed. Taken FROM the level's fill rather than named as a ramp step, because a level is not a ramp step in both schemes |\n", joinTokens("--elevation-", elevationStateNames()))
	fmt.Fprintf(&b, "| `--shadow-<level>` | %s | dp box-shadows — the OPT-IN cue for floating transients (menus, dialogs, tooltips) layered over the tonal fill; resting surfaces use the fill alone |\n", joinTokens("--shadow-", elevationNames()))
	fmt.Fprintf(&b, "| `--ease-<name>` | %s | MD3 easing presets as `cubic-bezier()`; emphasized is the documented single-bezier stand-in for MD3's two-segment path |\n", joinTokens("--ease-", easeNames()))
	fmt.Fprintf(&b, "| `--duration-<stop>` | %s | MD3-pinned duration stops, ms; the reduce-motion variant zeroes them |\n", joinTokens("--duration-", durationNames()))
	b.WriteString("| interaction states | `--focus-ring-width`, `--state-disabled-opacity` | the ring's 2 px stroke and the disabled fade fraction for `color-mix()` — both mode-invariant, unlike the ring's colour, which is measured against a surface that flips and so sits with the colours above |\n")
	b.WriteString("| scrim | `--color-scrim` | the modal backdrop dimmer: translucent black, identical in both modes — a scrim dims by reducing luminance, so it never flips with `.dark`. The alpha is the sRGB-compositing equivalent of the Gio pattern's 50% linear-space black |\n\n")

	b.WriteString("## Step purposes\n\n" +
		"| Step | Job |\n| --- | --- |\n" +
		"| 100 | tinted fill · the window's backdrop |\n" +
		"| 200 | tinted fill · one step off the backdrop |\n" +
		"| 300 | hover · subtle border, separator |\n" +
		"| 400 / 600 / 800 | intermediate steps; interaction states walk through them |\n" +
		"| 500 | mid-value reference · strong border |\n" +
		"| 700 | low-contrast text (Lc ≥ 60) · pressed |\n" +
		"| 900 | high-contrast body text (Lc ≥ 90) · pressed |\n\n" +
		"The pinned base — not a ramp step — is the solid fill; hover and pressed on a\n" +
		"solid walk one and two steps from the pin toward 900.\n\n")

	b.WriteString("## Component classes\n\n" +
		"`styles.css` ends with the component class layer, defined over the tokens\n" +
		"above — no literal colours anywhere, the only literal lengths being the\n" +
		"component constants the Gio side also hardcodes (the 20 dp checkbox/radio\n" +
		"glyph, its 10 dp dot, the 16 dp dropdown chevron, the 1/2 dp input\n" +
		"borders) — so it re-brands, flips to `.dark` and densifies to `.compact`\n" +
		"with the sheet. Every pointer/keyboard state rule carries a forcing twin\n" +
		"class (`.is-hover`, `.is-active`, `.is-focus`, `.is-checked`) grouped into\n" +
		"the same rule, so a static page can show a state with exactly the live\n" +
		"declarations; disabled is forced with the native attribute.\n\n" +
		"`.btn` is the button, **filled** by default: the accent pin under its\n" +
		"on-colour. Two modifier classes select the less pronounced emphasis\n" +
		"variants — `.btn.tonal` (the accent's tint, `--color-btn-tonal-fill` under\n" +
		"`--color-btn-tonal`: the same recipe `.badge` wears, one hue at two\n" +
		"strengths) and `.btn.ghost` (no fill at rest; neutral 700 text).\n" +
		"Interaction states resolve as the step walks above: hover walks one step\n" +
		"(`:hover`), pressed and selected two (`:active`, `.selected`); a filled\n" +
		"button's solid fill walks via the emitted `--color-accent-hover` /\n" +
		"`--color-accent-pressed` stops, and a tonal button through its own\n" +
		"`-hover` and `-active` pairs, whose foreground moves with the fill.\n" +
		"Keyboard focus (`:focus-visible`) keeps the resting fill and draws the\n" +
		"ring: `--focus-ring-width` of `--color-focus-ring`, the one ring the\n" +
		"scheme carries — the step of the primary ramp nearest its mid-value step\n" +
		"that reaches 3:1 against every level at once, so a control wears the same\n" +
		"ring wherever it is put. It also parts from every resting border in\n" +
		"luminance rather than in hue alone, so focus stays findable where a\n" +
		"display or a system setting takes the colour away, and it is never the\n" +
		"accent fill itself, which is what a checked control already paints.\n" +
		"`--color-focus-ring-on-accent` is the sole exception, for the ring a\n" +
		"filled button insets in its own fill: that fill is a step of the primary\n" +
		"ramp too, and the scheme's ring cannot read on it. Same ring, same width,\n" +
		"same 3:1 floor in every variant. Disabled (`:disabled`) fades each colour\n" +
		"to `--state-disabled-opacity` of its alpha. A ghost has no selected\n" +
		"treatment: it stays the least pronounced. `.btn.icon` is the icon-only\n" +
		"form: a square the density's control height on a side, the glyph (an\n" +
		"inline SVG on `currentColor`) inset by the density's vertical\n" +
		"padding.\n\n" +
		"`.badge` is the inline annotation: `label-medium` text over a tinted field\n" +
		"of its own hue. One hue at two strengths — a pale fill for the field and\n" +
		"the same hue at reading strength for the word — and never the inverted\n" +
		"pairing, which is what `.btn` uses and what a badge must not claim to be.\n" +
		"No boundary and no vertical padding, so its height is the role's line box;\n" +
		"the side padding is `--space-2` and the corner is `--radius-base`,\n" +
		"deliberately not the pill `.chip` wears. The default is the plain category\n" +
		"label; `.badge.success` / `.badge.warning` / `.badge.error` /\n" +
		"`.badge.info` are the four statuses, differing in hue alone. Both halves\n" +
		"are tokens because both are derived against a surface rather than named on\n" +
		"a ramp — the fill against the page, the foreground against the fill.\n" +
		"Compose them for status; never inline-style a status colour. A badge is\n" +
		"read, not used: no interaction states.\n\n" +
		"The form controls dress native elements — no script anywhere:\n" +
		"`.input` (text `<input>`, and `<select class=\"input select\">` inside a\n" +
		"`.select-wrap` for the chevron), `.checkbox` and `.radio` on their native\n" +
		"input types with `appearance: none`. They resolve exactly as\n" +
		"`components/input` does: the Surface fill under `body-large` text,\n" +
		"`--color-control-border` on the resting edge of all four controls,\n" +
		"neutral 700 placeholder and chevron, focus promoting the border to the\n" +
		"ring (2 dp on the text field, the shared outline on checkbox/radio),\n" +
		"disabled fading every colour via `color-mix()`. That border is the\n" +
		"neutral step the ramp measures as reaching 3:1 against the window\n" +
		"backdrop, which is 600 in the light scheme and 500 in the dark; the named\n" +
		"step it replaced read below the floor in one of them, at 2.67:1 in the\n" +
		"scheme most people read in. The edge follows the control into a raised\n" +
		"host: a surface that fills a deeper level declares `--surface-border`\n" +
		"beside its own fill, the rules name it with the paper's own token as\n" +
		"the fallback, and every control inside re-derives — the same walk\n" +
		"against the same fill the host measures its own outline against, which\n" +
		"is why a checkbox in a dialog wears the dialog's edge. In the dark\n" +
		"scheme the page's own step reads 2.62:1 over a level-2 fill and 1.80:1\n" +
		"over a level-3 one, both under the floor; in the light scheme it clears\n" +
		"every level and the handed-down token repeats. The ring does not\n" +
		"follow, because it never left: it is measured against every level at\n" +
		"once and is one colour for the scheme.\n" +
		"Checked, the box is the accent fill under a check mark in the\n" +
		"on-accent pin, drawn from the icon set's grid as two gradient bands — a\n" +
		"fill says a colour was applied and only the mark says what it means. The\n" +
		"radio's selected state is the accent ring and 10 dp dot around a Surface\n" +
		"gap.\n\n")

	b.WriteString("## Elevation: default vs opt-in\n\n" +
		"Elevation is tonal, and it climbs toward the light: **in both schemes,\n" +
		"every level is lighter than the one beneath it.** One perceptual rule,\n" +
		"no second rule for the dark scheme and no mirror — a surface nearer the\n" +
		"viewer catches more light, and reflectance does not invert when the room\n" +
		"goes dark. Six levels, counted from the backdrop up toward the reader:\n\n" +
		"| Level | What wears it |\n| --- | --- |\n" +
		"| `--elevation-backdrop` | nothing: the bare window plane, showing wherever nothing stands; the window's darkest region |\n" +
		"| `--elevation-chrome` | the window's furniture — navbar, toolbar, sidebar, inspector, status bar, pane |\n" +
		"| `--elevation-0` | the content surface, the bg pin |\n" +
		"| `--elevation-1` | raised on the content — cards, code fences, text fields; the raise walked from `--elevation-0`, not a table entry |\n" +
		"| `--elevation-2` | floating — dialogs, toasts |\n" +
		"| `--elevation-3` | floating, nearest the scheme's light extreme — menus, popovers, tooltips |\n\n" +
		"Read that down and the fill gets lighter, in `:root` and in `.dark`\n" +
		"alike. Chrome is window-scale only: the trim inside a component or a\n" +
		"pattern — a card's header, a dialog's footer — is that thing's\n" +
		"structure and takes no level of its own. The chrome level is the one\n" +
		"the ramp does not place: its step under the content is measured off the\n" +
		"platform rather than derived, and the two schemes measure\n" +
		"differently — about 4.9 L\\* under light content, about 1.5 under dark,\n" +
		"where a full ramp step would read as a hole rather than as furniture.\n" +
		"That asymmetry is the platform's own, not a rule mirrored between the\n" +
		"schemes. The backdrop takes that step scaled by the ramp's own\n" +
		"proportion, because no platform capture shows a window plane beneath\n" +
		"its furniture to measure. A chrome region that floats is still chrome\n" +
		"and still fills at the chrome level: what says it is a floating object\n" +
		"is its own hairline edge and its shadow, never a lighter fill.\n" +
		"The levels stop at 3: desktop has no six-deep stack. Note the\n" +
		"sizes — a light scheme has spent almost all of the tonal axis on its\n" +
		"content, so its levels above the content are separated by a fraction of\n" +
		"an L\\* and the derived line (`--elevation-<level>-hairline`,\n" +
		"`--dialog-border`, `--popover-border`) is what says where a surface is.\n" +
		"That is what the desktop applications this system is judged against\n" +
		"measure too.\n\n" +
		"The surface fill is the **default** cue. The dp shadow is the **opt-in**\n" +
		"secondary cue, reserved for floating transients — menus, dialogs,\n" +
		"tooltips — which layer `--shadow-N` over their tonal fill. Resting\n" +
		"surfaces never cast one.\n\n")

	b.WriteString("## Density\n\n" +
		"Two published settings, one variable family: comfortable (36 dp controls,\n" +
		"32 dp chips, 16/8 dp padding) is the `:root` default; compact (28 dp\n" +
		"controls, 24 dp chips, 12/6 dp padding) is the `.compact` class override,\n" +
		"scoping to any subtree the way `.dark` scopes colours. The chip height is\n" +
		"the control height less 4 dp in both settings — one relation, not a second\n" +
		"scale. `--density-min-hit-target` (44 dp, WCAG 2.5.5) is deliberately not\n" +
		"overridden: compact shrinks the drawn control, never the clickable area.\n" +
		"`theme.json` records both settings' metrics plus which one the theme runs.\n\n")

	b.WriteString("## Motion\n\n" +
		"The MD3 easing presets are emitted as `cubic-bezier()` variables and the\n" +
		"five duration stops in ms, each pinned to one MD3 duration role. The spring\n" +
		"presets (default/snappy/gentle) are Go-side damped-oscillator physics with\n" +
		"no CSS counterpart, so they live only in `theme.json`'s motion parameters.\n" +
		"Under the OS reduce-motion preference the theme emits the same scale with\n" +
		"every duration zeroed; the sheet is generated from the non-reduced scale.\n\n")

	b.WriteString("## Reproducibility\n\n" +
		"`theme.json` records the seed (hex plus its OKLCh hue and sat), the pinned role\n" +
		"hexes per mode, the faces, the base radius, the measured lightness scales, both\n" +
		"density settings' metrics, the elevation model (surface steps and shadow dps\n" +
		"per level) and the motion set (durations, easings, springs).\n" +
		"`FromSeed(seed)` regenerates every ramp and pin from the seed alone — a\n" +
		"round-trip test in `theme/export` asserts it — so the file, not this text,\n" +
		"is the contract. To rebrand, rerun `vg-tokens -seed #rrggbb`; every page here\n" +
		"reflows because nothing in them is hard-coded.\n\n" +
		"Fonts: the tokens name " + s.Typography.BodyLarge.Typeface + " (and " + s.Typography.Code.Typeface + " for code); the pages fall\n" +
		"back to system faces when they are not installed. An increased-contrast palette variant exists Go-side\n" +
		"(`tokens.FromSeedHighContrast`, driven by the OS contrast preference); it is\n" +
		"not part of this export.\n")

	return b.String()
}

// spaceNames, radiusNames and elevationNames list each scale's key names in
// sheet order, for the readme's enumerations.
func spaceNames() []string {
	names := make([]string, len(spaceKeys))
	for i, k := range spaceKeys {
		names[i] = k.name
	}
	return names
}

func radiusNames() []string {
	names := make([]string, len(radiusKeys))
	for i, k := range radiusKeys {
		names[i] = k.name
	}
	return names
}

func elevationNames() []string {
	names := make([]string, len(elevationLevels))
	for i, k := range elevationLevels {
		names[i] = k.name
	}
	return names
}

// elevationStateNames lists each level's interaction walk in sheet order —
// backdrop-hover, backdrop-active, 0-hover, and so on. The walk is a family
// of its own because a level is not a ramp step in both schemes, so a state
// taken from a level cannot be spelled as that step's neighbour.
// elevationSeamNames lists the seam each standable level owes what stands on
// it, in sheet order. The backdrop is absent: nothing stands on it.
func elevationSeamNames() []string {
	names := make([]string, 0, len(standableLevels))
	for _, k := range standableLevels {
		names = append(names, k.name+"-seam")
	}
	return names
}

// elevationHairlineNames lists the hairline each standable level's own fill
// is parted from itself by, in sheet order. The backdrop is absent: nothing
// is grouped on it.
func elevationHairlineNames() []string {
	names := make([]string, 0, len(standableLevels))
	for _, k := range standableLevels {
		names = append(names, k.name+"-hairline")
	}
	return names
}

func elevationStateNames() []string {
	names := make([]string, 0, 2*len(elevationLevels))
	for _, k := range elevationLevels {
		names = append(names, k.name+"-hover", k.name+"-active")
	}
	return names
}

// densityNames, easeNames and durationNames list the density metric, easing
// preset and duration stop names in sheet order, for the readme's
// enumerations.
func densityNames() []string {
	names := make([]string, len(densityMetrics))
	for i, m := range densityMetrics {
		names[i] = m.name
	}
	return names
}

func easeNames() []string {
	names := make([]string, len(easeRoles))
	for i, r := range easeRoles {
		names[i] = r.name
	}
	return names
}

func durationNames() []string {
	names := make([]string, len(durationStops))
	for i, s := range durationStops {
		names[i] = s.name
	}
	return names
}

// joinTokens renders a comma-separated code list of prefix+name tokens.
func joinTokens(prefix string, names []string) string {
	out := make([]string, len(names))
	for i, n := range names {
		out[i] = "`" + prefix + n + "`"
	}
	return strings.Join(out, ", ")
}
